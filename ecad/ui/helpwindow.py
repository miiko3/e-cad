def anchor_for(title: str) -> str:
    """Имя HTML-якоря блока инструкции (одинаково для списка и текста)."""
    return re.sub(r"[^0-9A-Za-zА-Яа-яЁё]+", "_", title).strip("_")


def instructions_html() -> str:
    def h(level: int, text: str) -> str:
        sizes = {1: 21, 2: 17, 3: 14}
        return (f'<a name="{anchor_for(text)}"></a>'
                f'<h{level} style="color:#7ab6ff; margin:14px 0 6px 0; '
                f'font-size:{sizes[level]}px;">{text}</h{level}>')

    def p(text: str) -> str:
        return f'<p style="line-height:1.45; margin:4px 0;">{text}</p>'

    def table(rows) -> str:
        """Таблица в виде компактного списка — QTextBrowser не поддерживает
        нормальные CSS-таблицы, поэтому строки выводим списком."""
        out = ['<div style="margin:8px 0 12px 0;">']
        head, *body = rows
        out.append('<div style="background:#26313d; color:#cfe3ff; font-weight:600; '
                   'padding:5px 9px; border-radius:8px 8px 0 0;">'
                   + "  ·  ".join(str(c) for c in head) + '</div>')
        for i, row in enumerate(body):
            bg = "#1b1f24" if i % 2 else "#20252b"
            cells = []
            for j, c in enumerate(row):
                if j == 0:
                    cells.append(f'<b style="color:#9ecbff;">{c}</b>')
                elif j == 1:
                    cells.append(f'<span style="color:#ffd28a;">{c}</span>')
                else:
                    cells.append(str(c))
            out.append(f'<div style="background:{bg}; padding:4px 9px; '
                       f'border-left:1px solid #39424d; border-right:1px solid #39424d;">'
                       + "  ·  ".join(cells) + '</div>')
        out.append('<div style="height:2px; background:#39424d; border-radius:0 0 8px 8px;">'
                   '</div></div>')
        return "".join(out)

    def ul(items) -> str:
        return '<ul style="line-height:1.45;">' + "".join(f"<li>{i}</li>" for i in items) + "</ul>"

