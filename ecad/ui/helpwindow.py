class HelpWindow(QDialog):
    """Отдельный блок «Инструкция по использованию»."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle(f"{APP} — Инструкция по использованию")
        self.resize(1080, 720)
        v = QVBoxLayout(self)
        v.setContentsMargins(14, 12, 14, 12)
        v.setSpacing(8)
        self.list = QListWidget()
        self.list.setMaximumWidth(230)
        self.view = QTextBrowser()
        self.view.setOpenExternalLinks(True)
        self.view.setHtml(instructions_html())
        for title in ["1. Установка и запуск", "2. Структура интерфейса", "3. Инструменты (16 режимов)",
                      "4. Слои платы", "5. Сетка, привязка и единицы", "6. Порядок работы над платой",
                      "7. Авто-земля и термобарьеры", "8. DRC — проверка условий",
                      "9. Компоненты, макросы, Pick+Place", "10. Экспорт для производства",
                      "11. Горячие клавиши", "12. Практические советы", "13. Ограничения"]:
            it = QListWidgetItem(title)
            it.setData(Qt.ItemDataRole.UserRole, anchor_for("Блок " + title))
            self.list.addItem(it)
        self.list.currentRowChanged.connect(self._jump)
        self.list.setCurrentRow(0)
        h = QHBoxLayout()
        h.addWidget(self.list)
        h.addWidget(self.view, 1)
        v.addLayout(h, 1)
        row = QHBoxLayout()
        b = QPushButton("О программе и авторе (блок «Актор»)")
        b.clicked.connect(self._about)
        b2 = QPushButton("Закрыть")
        b2.setObjectName("Primary")
        b2.clicked.connect(self.accept)
        row.addWidget(b)
        row.addStretch(1)
        row.addWidget(b2)
        v.addLayout(row)

    def _jump(self, row: int):
        it = self.list.item(row)
        if it is None:
            return
        anchor = it.data(Qt.ItemDataRole.UserRole)
        self.view.scrollToAnchor(anchor)
        sb = self.view.verticalScrollBar()
        sb.setValue(sb.value())          # Qt иногда не применяет прокрутку сразу

    def _about(self):
        from .about import AboutDialog
        AboutDialog(self).exec()